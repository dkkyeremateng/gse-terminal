#!/usr/bin/env node
/**
 * Generates src/lib/api/types-generated.ts from the live Go server's
 * OpenAPI spec at /v1/openapi.json.
 *
 * Usage:
 *   npm run gen:api                    # default: http://localhost:8080
 *   API_URL=https://prod npm run gen:api
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../src/lib/api/types-generated.ts')
const url = `${process.env.API_URL ?? 'http://localhost:8080'}/v1/openapi.json`

console.log(`[gen:api] fetching ${url}`)

try {
  const ast = await openapiTS(new URL(url), { exportType: true })
  const banner =
    '/* eslint-disable */\n' +
    '/**\n * AUTO-GENERATED by scripts/gen-api-types.mjs.\n * Do not edit by hand. Run `npm run gen:api` to refresh.\n */\n\n'
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, banner + astToString(ast), 'utf8')
  console.log(`[gen:api] wrote ${out}`)
} catch (err) {
  console.error(`[gen:api] failed: ${err?.message ?? err}`)
  console.error('[gen:api] is the Go server running on the API_URL host?')
  process.exit(1)
}
